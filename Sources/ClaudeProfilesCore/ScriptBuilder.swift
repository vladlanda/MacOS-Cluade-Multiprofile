import Foundation

/// Everything the generated terminal script needs. Paths must be absolute.
public struct TerminalScriptRequest: Equatable {
    public var profileName: String
    /// Becomes CLAUDE_CONFIG_DIR.
    public var configDirectory: String
    public var workingDirectory: String
    public var unsetAPIKey: Bool
    /// Appended to PATH so `claude` is found even if the user's shell setup doesn't add it.
    public var extraPathDirectories: [String]

    public static let defaultExtraPathDirectories = [
        "$HOME/.local/bin", "$HOME/.claude/local", "/opt/homebrew/bin", "/usr/local/bin",
    ]

    public init(
        profileName: String,
        configDirectory: String,
        workingDirectory: String,
        unsetAPIKey: Bool,
        extraPathDirectories: [String] = TerminalScriptRequest.defaultExtraPathDirectories
    ) {
        self.profileName = profileName
        self.configDirectory = configDirectory
        self.workingDirectory = workingDirectory
        self.unsetAPIKey = unsetAPIKey
        self.extraPathDirectories = extraPathDirectories
    }
}

public enum ScriptBuilderError: LocalizedError, Equatable {
    case controlCharacters(field: String)
    case notAbsolute(field: String)

    public var errorDescription: String? {
        switch self {
        case .controlCharacters(let field): "The \(field) path contains control characters (such as a line break)."
        case .notAbsolute(let field): "The \(field) path isn't a full path."
        }
    }
}

/// Builds the bash script that opens Claude Code for one profile.
///
/// Every value from the user (name, paths) is assigned once to a shell variable using
/// single-quote quoting and is only ever expanded inside double quotes, so spaces, quotes,
/// `$`, backticks and globs are inert. The profile name is only passed to printf as an
/// argument, never as the format string.
public enum ScriptBuilder {
    public static let installDocsURL = "https://docs.claude.com/en/docs/claude-code/overview"

    public static func build(_ request: TerminalScriptRequest) throws -> String {
        try validatePath(request.configDirectory, field: "Claude Code config folder")
        try validatePath(request.workingDirectory, field: "working folder")

        var lines: [String] = [
            "#!/bin/bash",
            "# Generated by Claude Profiles: opens Claude Code signed in to one profile.",
            "# The script deletes itself when it starts.",
            "rm -f -- \"$0\"",
            "",
            "PROFILE_NAME=\(shellQuote(displayName(request.profileName)))",
            "PROFILE_CONFIG_DIR=\(shellQuote(request.configDirectory))",
            "PROFILE_WORK_DIR=\(shellQuote(request.workingDirectory))",
            "",
            "export CLAUDE_CONFIG_DIR=\"$PROFILE_CONFIG_DIR\"",
            "# Overrides CLAUDE_CONFIG_DIR for the Keychain login; would make profiles share one account.",
            "unset CLAUDE_SECURESTORAGE_CONFIG_DIR",
        ]
        if request.unsetAPIKey {
            lines.append("# A set API key takes precedence over the account signed in with /login.")
            lines.append("unset ANTHROPIC_API_KEY")
        }
        if !request.extraPathDirectories.isEmpty {
            // These are fixed by the app (not user input) and may reference $HOME on purpose.
            let extra = request.extraPathDirectories.map { "\"\($0)\"" }.joined(separator: ":")
            lines.append("PATH=\"$PATH\":\(extra)")
            lines.append("export PATH")
        }

        lines += [
            "",
            "printf '\\033]0;Claude \u{00B7} %s\\007' \"$PROFILE_NAME\"",
            "",
            "if ! cd -- \"$PROFILE_WORK_DIR\" 2>/dev/null; then",
            "  printf 'Folder not found: %s\\nStarting in your home folder instead.\\n' \"$PROFILE_WORK_DIR\"",
            "  cd -- \"$HOME\" || exit 1",
            "fi",
            "",
            "printf '\\n  Claude profile: %s\\n  Config folder:  %s\\n\\n' \"$PROFILE_NAME\" \"$CLAUDE_CONFIG_DIR\"",
            "printf '  First time? Run /login. Run /status to confirm the account.\\n\\n'",
            "",
            "if ! command -v claude >/dev/null 2>&1; then",
            "  printf 'Claude Code (the \"claude\" command) was not found.\\n'",
            "  printf 'Install it: %s\\n\\n' \(shellQuote(installDocsURL))",
            "  printf 'Press any key to close.\\n'",
            "  read -r -s -n 1 _",
            "  exit 1",
            "fi",
            "",
            "while :; do",
            "  claude",
            "  printf '\\nClaude Code exited. Press Return to start it again, or close this window.\\n'",
            "  read -r _ || break",
            "done",
        ]
        return lines.joined(separator: "\n") + "\n"
    }

    /// POSIX single-quote quoting: the only character that needs care is `'` itself.
    public static func shellQuote(_ value: String) -> String {
        "'" + value.replacingOccurrences(of: "'", with: "'\\''") + "'"
    }

    /// The name is shown in the title bar and banner; control characters (newlines, ESC, BEL…)
    /// could break out of the title escape sequence, so they become spaces.
    public static func displayName(_ name: String) -> String {
        var scalars = String.UnicodeScalarView()
        for scalar in name.unicodeScalars {
            scalars.append(isControl(scalar) ? " " : scalar)
        }
        let cleaned = String(scalars).trimmingCharacters(in: .whitespaces)
        return cleaned.isEmpty ? "Profile" : String(cleaned.prefix(100))
    }

    static func validatePath(_ path: String, field: String) throws {
        if path.unicodeScalars.contains(where: isControl) {
            throw ScriptBuilderError.controlCharacters(field: field)
        }
        guard path.hasPrefix("/") else { throw ScriptBuilderError.notAbsolute(field: field) }
    }

    private static func isControl(_ scalar: Unicode.Scalar) -> Bool {
        switch scalar.properties.generalCategory {
        case .control, .lineSeparator, .paragraphSeparator: true
        default: false
        }
    }
}
